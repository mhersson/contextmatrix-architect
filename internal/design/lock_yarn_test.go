const yarnClassicFixture = `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1


"@acme/tokens@^2.0.0":
  version "2.0.1"
  resolved "https://registry.example.test/@acme/tokens/-/tokens-2.0.1.tgz#tok201"
  integrity sha512-tok201

"@acme/ui@^1.2.0", "@acme/ui@^1.2.1":
  version "1.2.3"
  resolved "https://registry.example.test/@acme/ui/-/ui-1.2.3.tgz#abc"
  integrity sha512-ui123
  dependencies:
    "@acme/tokens" "^2.0.0"
    left-pad "^1.0.0"
  optionalDependencies:
    fsevents "^2.0.0"

left-pad@^1.0.0, left-pad@~1.0.1:
  version "1.0.2"
  resolved "https://registry.example.test/left-pad/-/left-pad-1.0.2.tgz#lp102"
  integrity sha512-lp102

"ui-cjs@npm:@acme/ui@^1.2.0":
  version "1.2.3"
  resolved "https://registry.example.test/@acme/ui/-/ui-1.2.3.tgz#abc"
  integrity sha512-ui123
`

func TestYarnClassicLock(t *testing.T) {
	root := t.TempDir()
	writeTree(t, root, map[string]string{"yarn.lock": yarnClassicFixture})

	lock, err := readLockfile(root)
	require.NoError(t, err)
	require.NotNil(t, lock)
	assert.True(t, lock.checksummed())

	ui, ok := lock.fromRoot("", "@acme/ui", "^1.2.1")
	require.True(t, ok)

	tests := []struct {
		name     string
		resolve  func() (locked, bool)
		wantOK   bool
		wantName string
		wantVer  string
		wantFull string // "<resolved fragment>|<integrity suffix>"
	}{
		{
			name:    "a descriptor sharing an entry resolves with its tarball",
			resolve: func() (locked, bool) { return lock.fromRoot("", "@acme/ui", "^1.2.1") },
			wantOK:  true, wantName: "@acme/ui", wantVer: "1.2.3", wantFull: "abc|ui123",
		},
		{
			name:    "the other descriptor of the entry resolves to it too",
			resolve: func() (locked, bool) { return lock.fromRoot("frontend", "@acme/ui", "^1.2.0") },
			wantOK:  true, wantName: "@acme/ui", wantVer: "1.2.3", wantFull: "abc|ui123",
		},
		{
			name:    "an unquoted header lists several descriptors",
			resolve: func() (locked, bool) { return lock.fromRoot("", "left-pad", "~1.0.1") },
			wantOK:  true, wantName: "left-pad", wantVer: "1.0.2", wantFull: "lp102|lp102",
		},
		{
			name:    "a dependency resolves through the parent's dependencies",
			resolve: func() (locked, bool) { return lock.fromPackage(ui, "@acme/tokens") },
			wantOK:  true, wantName: "@acme/tokens", wantVer: "2.0.1", wantFull: "tok201|tok201",
		},
		{
			name:    "an alias resolves to the real package name",
			resolve: func() (locked, bool) { return lock.fromRoot("", "ui-cjs", "npm:@acme/ui@^1.2.0") },
			wantOK:  true, wantName: "@acme/ui", wantVer: "1.2.3", wantFull: "abc|ui123",
		},
		{
			name:    "a range no descriptor records is not found",
			resolve: func() (locked, bool) { return lock.fromRoot("", "@acme/ui", "^9.0.0") },
		},
		{
			name:    "a name that is only a path prefix is not found",
			resolve: func() (locked, bool) { return lock.fromRoot("", "../@acme/ui", "^1.2.0") },
		},
		{
			name:    "an optional dependency is not a dependency",
			resolve: func() (locked, bool) { return lock.fromPackage(ui, "fsevents") },
		},
		{
			name:    "a dependency the parent does not declare is not found",
			resolve: func() (locked, bool) { return lock.fromPackage(ui, "@acme/missing") },
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got, ok := tt.resolve()
			require.Equal(t, tt.wantOK, ok)

			if !tt.wantOK {
				return
			}

			assert.Equal(t, tt.wantName, got.Name)
			assert.Equal(t, tt.wantVer, got.Version)
			assert.False(t, got.Local)

			fragment, integrity, _ := strings.Cut(tt.wantFull, "|")
			assert.Equal(t, "sha512-"+integrity, got.Integrity)
			assert.True(t, strings.HasPrefix(got.Resolved, "https://registry.example.test/"+tt.wantName+"/-/"))
			assert.True(t, strings.HasSuffix(got.Resolved, "#"+fragment))
		})
	}
}

