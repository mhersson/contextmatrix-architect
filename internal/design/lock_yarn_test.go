func TestYarnBerryLock(t *testing.T) {
	root := t.TempDir()
	writeTree(t, root, map[string]string{"yarn.lock": yarnBerryFixture})

	lock, err := readLockfile(root)
	require.NoError(t, err)
	require.NotNil(t, lock)
	assert.False(t, lock.checksummed())

	ui, ok := lock.fromRoot("frontend", "@acme/ui", "^1.2.0")
	require.True(t, ok)

	tests := []struct {
		name     string
		resolve  func() (locked, bool)
		wantOK   bool
		wantName string
		wantVer  string
		local    bool
	}{
		{
			name:    "a bare range resolves under the npm protocol",
			resolve: func() (locked, bool) { return lock.fromRoot("frontend", "@acme/ui", "^1.2.0") },
			wantOK:  true, wantName: "@acme/ui", wantVer: "1.2.3",
		},
		{
			name:    "a ranged protocol resolves as written",
			resolve: func() (locked, bool) { return lock.fromRoot("", "@acme/ui", "npm:^1.2.0") },
			wantOK:  true, wantName: "@acme/ui", wantVer: "1.2.3",
		},
		{
			name:    "a key lists several descriptors",
			resolve: func() (locked, bool) { return lock.fromRoot("", "left-pad", "~1.0.1") },
			wantOK:  true, wantName: "left-pad", wantVer: "1.0.2",
		},
		{
			name:    "a dependency resolves through the parent's dependencies",
			resolve: func() (locked, bool) { return lock.fromPackage(ui, "@acme/tokens") },
			wantOK:  true, wantName: "@acme/tokens", wantVer: "2.0.1",
		},
		{
			name:    "a workspace package is local",
			resolve: func() (locked, bool) { return lock.fromRoot("", "@acme/shared", "workspace:^") },
			wantOK:  true, wantName: "@acme/shared", wantVer: "0.0.0-use.local", local: true,
		},
		{
			name:    "an alias resolves to the real package name",
			resolve: func() (locked, bool) { return lock.fromRoot("", "string-width-cjs", "npm:string-width@^4.2.0") },
			wantOK:  true, wantName: "string-width", wantVer: "4.2.3",
		},
		{
			name:    "a range no descriptor records is not found",
			resolve: func() (locked, bool) { return lock.fromRoot("", "@acme/ui", "^9.0.0") },
		},
		{
			name:    "a name that is only a path prefix is not found",
			resolve: func() (locked, bool) { return lock.fromRoot("", "../@acme/ui", "^1.2.0") },
		},
		{
			name:    "the metadata key is not a package",
			resolve: func() (locked, bool) { return lock.fromRoot("", "__metadata", "*") },
		},
		{
			name:    "a dependency the parent does not declare is not found",
			resolve: func() (locked, bool) { return lock.fromPackage(ui, "@acme/missing") },
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got, ok := tt.resolve()
			require.Equal(t, tt.wantOK, ok)

			if !tt.wantOK {
				return
			}

			assert.Equal(t, tt.wantName, got.Name)
			assert.Equal(t, tt.wantVer, got.Version)
			assert.Equal(t, tt.local, got.Local)
			assert.Empty(t, got.Resolved)
			assert.Empty(t, got.Integrity)
		})
	}
}

